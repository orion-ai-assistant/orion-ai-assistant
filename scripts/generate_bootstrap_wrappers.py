"""Generate standalone launchers from canonical Python sources (no network).

Use --check in validation to detect drift. Compressed payload avoids the Windows
command-line length limit and contains only committed source, never user files.
"""
import argparse
import base64
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]


def generated():
    sources = [(ROOT / 'services/shared/installation_registry.py').read_text(encoding='utf-8'),
               (ROOT / 'scripts/bootstrap_installation.py').read_text(encoding='utf-8'),
               (ROOT / 'services/shared/installation_paths.py').read_text(encoding='utf-8')]
    payload = base64.b64encode(zlib.compress(json.dumps(sources).encode(), 9)).decode()
    runner = "import base64,json,zlib,sys,types; s=json.loads(zlib.decompress(base64.b64decode('" + payload + "'))); pkg=types.ModuleType('bundled'); pkg.__path__=[]; sys.modules['bundled']=pkg; r=types.ModuleType('bundled.installation_registry'); r.__package__='bundled'; sys.modules[r.__name__]=r; exec(compile(s[0],'bundled_registry.py','exec'),vars(r)); p=types.ModuleType('bundled.installation_paths'); p.__package__='bundled'; sys.modules[p.__name__]=p; exec(compile(s[2],'bundled_paths.py','exec'),vars(p)); b={'__name__':'bundled_bootstrap','_BUNDLED_PATHS':vars(p)}; exec(compile(s[1],'bundled_bootstrap.py','exec'),b); sys.exit(b['main'](registry_api=vars(r)))"
    ps = '''# Generated by scripts/generate_bootstrap_wrappers.py; edit canonical Python.
param(
    [ValidateSet("local", "docker")][string]$Mode = "docker",
    [string]$Root,
    [string]$ModelsPath,
    [string]$RegistryPath,
    [switch]$NonInteractive,
    [switch]$PlanOnly,
    [switch]$Browse
)
Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"
if ($Browse) {
    if ($NonInteractive -or $PlanOnly) { throw "Browse cannot be combined with silent/plan mode" }
    Add-Type -AssemblyName System.Windows.Forms
    $dialog = New-Object System.Windows.Forms.FolderBrowserDialog
    $dialog.Description = "Choose Orion installation root (Hub and Models subfolders)"
    try {
        if ($dialog.ShowDialog() -ne [System.Windows.Forms.DialogResult]::OK) { exit 1 }
        $Root = $dialog.SelectedPath
    } finally { $dialog.Dispose() }
}
$python = (Get-Command python -ErrorAction Stop).Source
$arguments = @("-c", '__RUNNER__', "--mode", $Mode)
if ($Root) { $arguments += @("--root", $Root) }
if ($ModelsPath) { $arguments += @("--models-path", $ModelsPath) }
if ($RegistryPath) { $arguments += @("--registry-path", $RegistryPath) }
if ($NonInteractive) { $arguments += "--non-interactive" }
if ($PlanOnly) { $arguments += "--plan-only" }
& $python @arguments
exit $LASTEXITCODE
'''.replace('__RUNNER__', runner.replace("'", "''"))
    sh = '''#!/usr/bin/env bash
# Generated by scripts/generate_bootstrap_wrappers.py; edit canonical Python.
set -euo pipefail
python_cmd=python3
if ! command -v "$python_cmd" >/dev/null 2>&1; then python_cmd=python; fi
args=("$@")
# Preserve the historical positional mode argument.
if [[ ${1:-} == local || ${1:-} == docker ]]; then
    args=(--mode "$1" "${@:2}")
fi
exec "$python_cmd" -c '__RUNNER__' "${args[@]}"
'''.replace('__RUNNER__', runner.replace("'", "'\"'\"'"))
    return {'install.ps1': ps, 'install.sh': sh}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for name, content in generated().items():
        path = ROOT / name
        if args.check:
            if path.read_text(encoding='utf-8') != content:
                drift.append(name)
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    if drift:
        raise SystemExit('Regenerate bootstrap wrappers: ' + ', '.join(drift))


if __name__ == '__main__':
    main()
